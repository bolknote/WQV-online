class Watch {
  opened = true; configured = true; baud = 115200; readPending = false; readerTask = null;
  txFrames = 0; rxBytes = 0; inEndpoint = 2; outEndpoint = 1; queued = []; sent = []; polls = [];
  receivedAt = null; turnaroundGaps = [];
  constructor({ corrupt = false, stuck = false, noClose = false, records = 2, current = false } = {}) {
    this.dump = concat(...Array.from({ length: records }, (_, i) => image(i))); this.count = records;
    this.corrupt = corrupt; this.stuck = stuck; this.noClose = noClose; this.current = current;
    this.device = {
      transferOut: async (endpoint, packet) => {
        if (this.receivedAt !== null) this.turnaroundGaps.push(performance.now() - this.receivedAt);
        assert.equal(endpoint, 1); assert.equal(this.readPending, false);
        assert.equal(packet[0], 0x55); assert.equal(packet[1], 0xaa); assert.equal(packet[2] | packet[3] << 8, packet.length - 4);
        const decoder = new WQV12Decoder(); decoder.feed(packet.slice(4)); assert.equal(decoder.frames.length, 1);
        this.respond(decoder.frames[0]); return { status: 'ok', bytesWritten: packet.length };
      },
      transferIn: async () => {
        if (this.stuck) return new Promise(() => {});
        const bytes = this.queued.shift() ?? b();
        if (bytes.length) this.receivedAt = performance.now();
        return { status: 'ok', data: new DataView(bytes.buffer, bytes.byteOffset, bytes.length) };
      },
    };
  }
  assertOpen() { assert.ok(this.opened); }
  async io(promise) { return promise; }
  async registers() { return b(4, 0, 0); }
  async close() { this.opened = false; }
  reply(address, control, data = b(), corrupt = false) {
    const raw = encodeWQV12(address, control, data);
    if (corrupt) raw[raw.length - 2] ^= 1;
    for (let p = 0; p < raw.length; p += 13) this.queued.push(raw.slice(p, p + 13));
  }
  respond(frame) {
    const { address, control, data } = frame; this.sent.push(frame);
    if (address === 255 && control === 0xb3) return this.reply(255, 0xa3, b(13, 57, 25, 128));
    if (address === 255 && control === 0x93) {
      assert.deepEqual(data, b(13, 57, 25, 128, 2)); this.stage = 'connected';
      this.reply(2, 0x63); this.reply(2, 0x63); return;
    }
    assert.equal(address, 2);
    if (control === 0x11 && this.stage === 'connected') return this.reply(2, 1);
    if (control === 0x10) { assert.deepEqual(data, b(this.current ? 0 : 1)); this.stage = 'header'; return this.reply(2, 0x21); }
    if (control === 0x11 && this.stage === 'header') return this.reply(2, 0x20, b(7, 0xfa, 0x1c, 0x3d, this.count));
    if (control === 0x32 && this.stage === 'header') { this.stage = 'photos'; this.index = 0; return this.reply(2, 0x41); }
    if (control === 0x53) { if (!this.noClose) this.reply(2, 0x63); return; }
    if ((control & 31) === 0x14) { if (!this.noClose) this.reply(2, 0x61); return; }
    if ((control & 31) === 0x11 && this.stage === 'photos') {
      const nr = control >>> 5; this.polls.push(control);
      if (this.previousNR !== nr) { if (this.previousNR !== undefined) this.index++; this.previousNR = nr; }
      const payload = this.dump.slice(this.index * 128, (this.index + 1) * 128), bad = this.corrupt && this.index === 3 && !this.badSent;
      if (bad) this.badSent = true;
      return this.reply(2, 0x40 | nr << 1, concat(b(5), payload), bad);
    }
    throw new Error('Unexpected host command ' + control.toString(16));
  }
}

function rawTransport(adapter) {
  adapter.device = null;
  adapter.registers = async () => { throw new Error('SigmaTel registers used on a raw SIR adapter'); };
  adapter.readSIR = async () => {
    const bytes = adapter.queued.shift() ?? b();
    if (bytes.length) adapter.receivedAt = performance.now();
    return bytes;
  };
  adapter.writeSIR = async wire => {
    assert.equal(adapter.readPending, false);
    if (adapter.receivedAt !== null) adapter.turnaroundGaps.push(performance.now() - adapter.receivedAt);
    assert.equal(wire[0], 0xc0); assert.equal(wire.at(-1), 0xc1);
    const decoder = new WQV12Decoder(); decoder.feed(wire);
    assert.equal(decoder.frames.length, 1); adapter.respond(decoder.frames[0]);
    return { status: 'ok', bytesWritten: wire.length };
  };
  return adapter;
}

