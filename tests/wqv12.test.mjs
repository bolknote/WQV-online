// The OTHERS SEND sequence is taken from the WQV-2 receiver documented by
// molefrog/casio-wqv-rcv. Explicit control tables keep this peer independent
// of the client's sequence-number arithmetic.
class SendingWatch extends Watch {
  constructor({ finalPoll = false, repeatHello = false, repeatPacket = false, badPacket = false,
    wrongEcho = false, shortImage = false, invalidSize = false, noClose = false } = {}) {
    super({ records: 1 });
    Object.assign(this, { finalPoll, repeatHello, repeatPacket, badPacket, wrongEcho, noClose });
    this.dump = shortImage ? image().slice(0, 128) : image();
    this.header = invalidSize ? hx('04fa1c3c') : hx('04fa1c3d');
    this.peerAddress = 0x60; this.stage = 'hello'; this.index = 0;
    this.reply(255, 0xb3);
  }
  nextPacket() {
    const controls = [0x32, 0x34, 0x36, 0x38, 0x3a, 0x3c, 0x3e, 0x30];
    if (this.index * 128 >= this.dump.length) {
      this.stage = 'finish'; this.reply(this.peerAddress, 0x31); return;
    }
    const data = concat(b(5), this.dump.slice(this.index * 128, (this.index + 1) * 128));
    if (this.badPacket && this.index === 3 && !this.badSent) {
      this.badSent = true; this.reply(this.peerAddress, controls[this.index % 8], data, true);
    }
    this.reply(this.peerAddress, controls[this.index % 8], data);
  }
  respond(frame) {
    const { address, control, data } = frame; this.sent.push(frame);
    if (this.stage === 'hello') {
      assert.equal(address, 255); assert.equal(control, 0xa3); assert.equal(data.length, 4);
      if (this.challenge) assert.deepEqual(data, this.challenge, 'repeat B3 must receive the original challenge');
      this.challenge = data.slice();
      if (this.repeatHello && !this.helloRepeated) {
        this.helloRepeated = true; this.reply(255, 0xb3); return;
      }
      const echo = data.slice(); if (this.wrongEcho) echo[0] ^= 1;
      this.stage = 'connect'; this.reply(255, 0x93, concat(echo, b(this.peerAddress))); return;
    }
    assert.equal(address, this.peerAddress);
    if (this.stage === 'connect') {
      assert.equal(control, 0x63); this.stage = 'ready'; this.reply(address, 0x11); return;
    }
    if (this.stage === 'ready') {
      assert.equal(control, 1); this.stage = 'header'; this.reply(address, 0x10, this.header); return;
    }
    if (this.stage === 'header') {
      assert.equal(control, 0x21); this.stage = 'poll'; this.reply(address, 0x11); return;
    }
    if (this.stage === 'poll') {
      assert.equal(control, 0x20); assert.deepEqual(data, b(6)); this.stage = 'photos'; this.nextPacket(); return;
    }
    if (this.stage === 'photos') {
      assert.equal(control, [0x41, 0x61, 0x81, 0xa1, 0xc1, 0xe1, 1, 0x21][this.index % 8]);
      assert.equal(data.length, 0);
      if (this.repeatPacket && this.index === 3 && !this.packetRepeated) {
        this.packetRepeated = true; this.nextPacket(); return;
      }
      this.index++; this.nextPacket(); return;
    }
    if (this.stage === 'finish') {
      assert.equal(control, 0x42); assert.deepEqual(data, b(6));
      if (this.noClose) return;
      this.stage = this.finalPoll ? 'final-poll' : 'close'; this.reply(address, this.finalPoll ? 0x51 : 0x53); return;
    }
    if (this.stage === 'final-poll') {
      assert.equal(control, 0x41); this.stage = 'close'; this.reply(address, 0x53); return;
    }
    assert.equal(this.stage, 'close'); assert.equal(control, 0x63); this.stage = 'closed';
  }
}

